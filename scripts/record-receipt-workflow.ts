import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { EvidenceDesk } from '../server/desk.ts';
import { createDeskServer } from '../server/http.ts';
import { RELEASE_QUESTION, type Packet } from '../server/handoff.ts';
// @ts-expect-error Use the actual browser exporter for this real local recording.
import { createReceipt } from '../src/api.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packetPath = path.resolve(root, process.argv[2] || '');
assert(packetPath.startsWith(root + path.sep), 'Choose a packet in this exact project.');
const packetBytes = await fs.readFile(packetPath), packet: Packet = JSON.parse(packetBytes.toString('utf8'));
assert.equal(packet.provenance, 'local-observation'); assert.equal(packet.revisions[0].dirty, false);
assert(packet.ci.every(row => row.outcome === 'passed')); assert.equal(packet.releases[0].decision, 'ready');
const out = path.join(root, '.local', 'receipt-demo', new Date().toISOString().replace(/[^0-9TZ]/g, ''));
await fs.mkdir(out, { recursive: true });
const config = (name: string) => ({ workspace: root, dataDir: path.join(out, name), distDir: path.join(root, 'dist'), allowNemotron: false, nemotronModel: 'disabled' });
let providerCalls = 0;
const noProvider = (async () => { providerCalls++; throw Error('Recording cannot contact a provider.'); }) as typeof fetch;
const desk = new EvidenceDesk(config('runtime'), noProvider), server = createDeskServer(desk);
await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
const app = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const blocked: string[] = [], pageErrors: string[] = [], shots: object[] = [], replies: object[] = [];
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, colorScheme: 'light', locale: 'en-US', timezoneId: 'UTC', serviceWorkers: 'block', recordVideo: { dir: out, size: { width: 1280, height: 720 } } });
await context.route('**/*', (route: any) => new URL(route.request().url()).origin === app ? route.continue() : (blocked.push(new URL(route.request().url()).origin), route.abort()));
const page = await context.newPage(), video = page.video();
page.on('pageerror', (error: Error) => pageErrors.push(error.message));
const pause = (seconds: number) => new Promise(resolve => setTimeout(resolve, seconds * 1000));
const post = async (route: string, body: unknown) => { const response = await fetch(app + route, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }); assert(response.ok); return response.json(); };
try {
  const loaded = await post('/api/handoff/import', packet);
  const answer = await post('/api/answer', { snapshotId: loaded.snapshot.id, question: RELEASE_QUESTION });
  assert.equal(answer.releaseDecision, 'ready'); assert.equal(answer.citations.length, 4);
  const receipt = createReceipt(loaded.snapshot, answer, answer.metrics, desk.status());
  const altered = structuredClone(receipt); altered.answer.releaseDecision = 'hold';
  const fakeClock = Date.now() - 2 * 3_600_000, synthetic = structuredClone(packet), stamp = new Date(fakeClock).toISOString();
  synthetic.provenance = 'synthetic-replay'; synthetic.project = 'synthetic-expired-receipt';
  synthetic.revisions.forEach(row => { row.commit = 'f'.repeat(40); row.observedAt = stamp; });
  synthetic.ci.forEach(row => { row.observedAt = stamp; row.detail = 'SYNTHETIC invented receipt for expiry demonstration, not a command run.'; });
  synthetic.releases.forEach(row => { row.observedAt = stamp; row.detail = 'SYNTHETIC historical recommendation, not deployment authorization.'; });
  const historicDesk = new EvidenceDesk(config('synthetic-clock-runtime'), noProvider, () => fakeClock);
  const historicLoaded = await historicDesk.importHandoff(synthetic), historicAnswer = await historicDesk.answer({ snapshotId: historicLoaded.snapshot.id, question: RELEASE_QUESTION });
  const historic = { ...createReceipt(historicLoaded.snapshot, historicAnswer, historicAnswer.metrics, historicDesk.status()), exportedAt: stamp };
  for (const [name, value] of [['actual', receipt], ['altered', altered], ['synthetic-expired', historic]] as const) await fs.writeFile(path.join(out, name + '.json'), JSON.stringify(value));
  const started = performance.now();
  const until = async (seconds: number) => pause(Math.max(0, seconds - (performance.now() - started) / 1000));
  const scroll = async (selector: string) => page.locator(selector).evaluate((element: HTMLElement) => element.scrollIntoView({ behavior: 'smooth', block: 'center' }));
  await page.goto(app); await page.getByRole('heading', { name: 'Evidence review', exact: true }).waitFor();
  await page.getByText('Verify a saved release review', { exact: true }).click();
  await scroll('.receipt-verifier');
  await until(6);
  async function check(value: unknown, expectedStatus: number) {
    await page.getByLabel('Exported v2 handoff receipt').fill(JSON.stringify(value));
    const responseWait = page.waitForResponse((response: any) => response.url() === app + '/api/receipt/verify');
    await page.getByRole('button', { name: 'Verify receipt', exact: true }).click();
    const response = await responseWait; assert.equal(response.status(), expectedStatus);
    const body = await response.json(); replies.push(body); return body;
  }
  let result = await check(receipt, 200); assert.equal(result.current.decision, 'ready');
  await scroll('.receipt-verification-result'); await pause(1);
  await page.screenshot({ path: path.join(out, 'valid.png') });
  shots.push({ from: 0, to: 18, kind: 'actual-current-local-observations', sourceCommit: packet.revisions[0].commit });
  await until(18);
  await scroll('#verify-receipt-json');
  result = await check(altered, 400); assert.equal(result.error.code, 'RECEIPT_DECISION');
  await page.getByRole('alert').filter({ hasText: 'do not match an isolated replay' }).waitFor();
  await pause(1); await page.screenshot({ path: path.join(out, 'rejected.png') });
  shots.push({ from: 18, to: 30, kind: 'deliberately-altered-copy-of-actual-receipt' });
  await until(30);
  result = await check(historic, 200); assert.equal(result.recorded.decision, 'ready'); assert.equal(result.current.status, 'abstained'); assert.equal(result.snapshotExpiredNow, true);
  await scroll('.receipt-verification-result'); await pause(1);
  await page.screenshot({ path: path.join(out, 'expired.png') });
  shots.push({ from: 30, to: 52, kind: 'explicitly-synthetic-expiry-case' });
  await until(44); await scroll('.receipt-verification-result p:last-child'); await until(52);
  await context.close(); await video.saveAs(path.join(out, 'receipt-workflow.webm'));

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'en-US', timezoneId: 'UTC', serviceWorkers: 'block' });
  const mobilePage = await mobile.newPage(); await mobilePage.goto(app);
  await mobilePage.getByText('Verify a saved release review', { exact: true }).click();
  await mobilePage.getByLabel('Exported v2 handoff receipt').fill(JSON.stringify(historic));
  await mobilePage.getByRole('button', { name: 'Verify receipt', exact: true }).click();
  await mobilePage.getByRole('heading', { name: 'Saved decision reproduced' }).waitFor();
  await mobilePage.locator('.receipt-verification-result').scrollIntoViewIfNeeded();
  const overflow = await mobilePage.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false); await mobilePage.screenshot({ path: path.join(out, 'mobile.png') }); await mobile.close();
  assert.equal(providerCalls, 0); assert.deepEqual(blocked, []); assert.deepEqual(pageErrors, []);
  await fs.writeFile(path.join(out, 'recording.json'), JSON.stringify({ createdAt: new Date().toISOString(), app: 'isolated real loopback product server', sourceCommit: packet.revisions[0].commit, packetSha256: createHash('sha256').update(packetBytes).digest('hex'), actualReceiptBytes: Buffer.byteLength(JSON.stringify(receipt)), providerCalls, blocked, pageErrors, mobileOverflow: overflow, plannedDurationSeconds: 52, shots, replies }, null, 2));
  await fs.writeFile(path.join(root, '.local', 'receipt-demo', 'latest.json'), JSON.stringify({ out }));
  console.log(JSON.stringify({ out, sourceCommit: packet.revisions[0].commit, providerCalls, mobileOverflow: overflow }));
} finally { await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); }
